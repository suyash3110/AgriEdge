export function formCopy(locale: string, text: string): string {
  return locale === "mr"
    ? ((marathi as Record<string, string>)[text] ?? text)
    : locale === "hi"
      ? (hindi[text] ?? text)
      : text;
}
export function formError(
  locale: string,
  code: string | undefined,
  message: string,
): string {
  if (locale === "mr")
    return code === "RESIDUE_DETAILS_REQUIRED"
      ? "अवशेषासाठी सामग्री, स्वरूप, नियोजित वापर आणि दूषितपणाची माहिती भरा."
      : ((marathi as Record<string, string>)[message] ??
          "विनंती पूर्ण झाली नाही. नोंद आणि भरलेली माहिती तपासून पुन्हा प्रयत्न करा.");
  if (locale !== "hi") return message;
  if (code === "RESIDUE_DETAILS_REQUIRED")
    return "अवशेष के लिए सामग्री, रूप, प्रस्तावित उपयोग और संदूषण की जानकारी भरें।";
  const translated = hindi[message];
  // Unknown errors use a localized fallback; error codes remain available for support.
  return (
    translated ??
    "अनुरोध पूरा नहीं हुआ। रिकॉर्ड और भरी हुई जानकारी जाँचकर फिर कोशिश करें।"
  );
}
